// ============================================================
// LOGIA — Worldbuilding importer
// Scans ../../세계관 (local only, gitignored) and emits
// src/seed-worldbuilding.local.js for the store to seed from.
//
//   folder layout  →  tags         [project, category]
//   [[wikilinks]]  →  kept as-is   (resolved by title in the store)
//   에셋 / 에셋 프롬 folders  →  skipped (adult asset prompts excluded)
//   empty files    →  skipped
//
// Run:  node scripts/import-worldbuilding.mjs
// ============================================================
import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, relative, basename, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..', '세계관');
const OUT = join(__dirname, '..', 'src', 'seed-worldbuilding.local.js');

// Folder names to skip entirely (adult image-generation prompts).
const SKIP_DIRS = new Set(['에셋', '에셋 프롬']);

// Strip a leading "01_" / "201_" / "01." numeric prefix and the .md suffix.
const clean = (s) => s.replace(/\.md$/i, '').replace(/^\d+[_.\s]*/, '').trim();

function walk(dir, acc = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (SKIP_DIRS.has(name)) continue;
      walk(full, acc);
    } else if (name.toLowerCase().endsWith('.md')) {
      acc.push(full);
    }
  }
  return acc;
}

const files = walk(ROOT);
const docs = [];
let skippedEmpty = 0;

files.forEach((full, i) => {
  const content = readFileSync(full, 'utf8').trim();
  if (!content) { skippedEmpty += 1; return; }

  const rel = relative(ROOT, full);
  const parts = rel.split(/[\\/]/);
  const project = clean(parts[0]);
  // category = the immediate parent folder, or '개요' for files directly under a project.
  const category = parts.length > 2 ? clean(parts[parts.length - 2]) : '개요';
  const title = clean(basename(full));

  docs.push({
    id: `wb-${String(i + 1).padStart(3, '0')}`,
    title,
    tags: [project, category],
    ago: i, // stable order; lower = treated as more recent by the store
    content,
  });
});

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  '// AUTO-GENERATED by scripts/import-worldbuilding.mjs — do not edit.\n' +
  '// Source: 세계관/ (local only, gitignored). Adult asset-prompt folders excluded.\n' +
  `export const WORLDBUILDING_DOCS = ${JSON.stringify(docs, null, 2)};\n`,
);

console.log(`imported ${docs.length} docs (skipped ${skippedEmpty} empty), → ${relative(join(__dirname, '..'), OUT)}`);
