// ============================================================
// LOGIA — Worldbuilding importer (unified thematic layout)
// Reads the reorganized 세계관/ (분류/시대/제목.md with YAML
// frontmatter) and emits src/seed-worldbuilding.local.js.
//   • frontmatter (분류·시대) → tags, then stripped from the body
//   • [[NN_제목]] links normalized (idempotent)
//   • per-분류 색인 docs generated + back-linked into each member,
//     so every doc is graph-connected; the 00_정전 codex provides
//     the thematic spine (세계 개요 is the hub).
//
// Run:  node scripts/import-worldbuilding.mjs
// ============================================================
import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, basename, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..', '세계관');
const OUT = join(__dirname, '..', 'src', 'seed-worldbuilding.local.js');

const NO_INDEX = new Set(['정전']); // codex is already interlinked

function walk(dir, acc = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, acc);
    else if (name.toLowerCase().endsWith('.md')) acc.push(full);
  }
  return acc;
}

function parseFrontmatter(raw) {
  const m = /^---\s*\n([\s\S]*?)\n---\s*\n?/.exec(raw);
  if (!m) return { meta: {}, body: raw };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const mm = /^([^:]+):\s*(.*)$/.exec(line.trim());
    if (mm) meta[mm[1].trim()] = mm[2].trim();
  }
  return { meta, body: raw.slice(m[0].length) };
}

const docs = [];
let ago = 100;
for (const full of walk(ROOT)) {
  const raw = readFileSync(full, 'utf8').trim();
  if (!raw) continue;
  const { meta, body } = parseFrontmatter(raw);
  const cat = meta['분류'] || '기타';
  const era = meta['시대'] || '양시대';
  const title = basename(full, '.md').trim();
  const content = body.replace(/\[\[\s*\d+[_.]\s*([^\]]+?)\s*\]\]/g, '[[$1]]').trim();
  docs.push({ id: `wb-${String(docs.length + 1).padStart(3, '0')}`, title, tags: [cat, era], ago: ago++, content });
}

// Per-분류 index docs + reciprocal back-links → guarantees graph connectivity.
const indexDocs = [];
const cats = [...new Set(docs.map((d) => d.tags[0]))].filter((c) => !NO_INDEX.has(c));
for (const cat of cats) {
  const members = docs.filter((d) => d.tags[0] === cat);
  members.forEach((m) => { m.content += `\n\n> 색인 · [[${cat} 색인]]`; });
  const list = members.map((m) => `- [[${m.title}]]`).sort().join('\n');
  indexDocs.push({
    id: `idx-${cat}`, title: `${cat} 색인`, tags: [cat, '색인'], ago: 9,
    content: `# ${cat} 색인\n\n[[세계 개요]] 아래 **${cat}** 문서 ${members.length}개.\n\n${list}`,
  });
}

const all = [...docs, ...indexDocs];

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  '// AUTO-GENERATED by scripts/import-worldbuilding.mjs — do not edit.\n' +
  '// Source: 세계관/ (local only, gitignored). Unified thematic layout.\n' +
  `export const WORLDBUILDING_DOCS = ${JSON.stringify(all, null, 2)};\n`,
);

console.log(`imported ${docs.length} docs + ${indexDocs.length} indexes = ${all.length}`);
console.log(`분류: ${cats.join(', ')}`);
